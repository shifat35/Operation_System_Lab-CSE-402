processes = [
    {"pid": "P1", "at": 0, "bt": 3, "pr": 3},
    {"pid": "P2", "at": 1, "bt": 4, "pr": 2},
    {"pid": "P3", "at": 2, "bt": 6, "pr": 4},
    {"pid": "P4", "at": 3, "bt": 4, "pr": 6},
    {"pid": "P5", "at": 5, "bt": 2, "pr": 10},
]

def non_preemptive(procs):
    procs = [dict(p) for p in procs]
    n = len(procs)
    completed = []
    time = 0
    done = set()
    while len(done) < n:
        ready = [p for p in procs if p["at"] <= time and p["pid"] not in done]
        if not ready:
            time += 1
            continue

        current = min(ready, key=lambda x: x["pr"])
        time += current["bt"]
        current["ct"] = time
        current["tat"] = current["ct"] - current["at"]
        current["wt"] = current["tat"] - current["bt"]
        completed.append(current)
        done.add(current["pid"])
    return completed

def preemptive(procs):
    procs = [dict(p) for p in procs]
    n = len(procs)
    remaining = {p["pid"]: p["bt"] for p in procs}
    time = 0
    completed = {}
    while len(completed) < n:
        ready = [p for p in procs if p["at"] <= time and remaining[p["pid"]] > 0]
        if not ready:
            time += 1
            continue

        current = min(ready, key=lambda x: x["pr"])
        remaining[current["pid"]] -= 1
        time += 1


        if remaining[current["pid"]] == 0:
            current["ct"] = time
            current["tat"] = current["ct"] - current["at"]
            current["wt"] = current["tat"] - current["bt"]
            completed[current["pid"]] = current
    return list(completed.values())


def show(results, title):
    print()
    print(title)
    print(f"{'PID':<5}{'AT':<5}{'BT':<5}{'PR':<5}{'CT':<5}{'TAT':<5}{'WT':<5}")
    total_tat = 0
    total_wt = 0
    for p in results:
        print(f"{p['pid']:<5}{p['at']:<5}{p['bt']:<5}{p['pr']:<5}{p['ct']:<5}{p['tat']:<5}{p['wt']:<5}")
        total_tat += p["tat"]
        total_wt += p["wt"]
    n = len(results)
    print(f"Average TAT = {total_tat/n:.2f} ms")
    print(f"Average WT = {total_wt/n:.2f} ms")


np_result = non_preemptive(processes)
show(sorted(np_result, key=lambda x: x["pid"]), "Non-Preemptive Priority")

p_result = preemptive(processes)
show(sorted(p_result, key=lambda x: x["pid"]), "Preemptive Priority")